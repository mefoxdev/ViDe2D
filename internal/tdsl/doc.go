// Пакет tdsl содержит лексер и парсер языка TrueDSL (файлы .tdsl).
//
// Спецификация: docs/truedsl/reference.md (раздел 11 — грамматика) и docs/truedsl/errors.md.
// Входная точка — Parse. Пакет ничего не знает о рантайме: имена и типы не проверяются.
//
// Места, где спецификация неоднозначна или противоречива, и принятые решения:
//
//   - Слова «turn» и «from» используются в грамматике, но не входят в список зарезервированных;
//     лексер считает их ключевыми. Имена свойств (x, y, text ...) и «mouse» лексер отдаёт как
//     обычные имена: их «занятость» (TD103) проверяет семантический анализ. «touching» — тоже имя,
//     в «when stop touching» парсер ждёт именно его.
//   - После точки допустимо любое слово, в том числе ключевое («mouse.held»).
//   - Название клавиши в «key ...» — любое слово (в том числе left, up) или текст в кавычках.
//   - Опечатка в направлении («move rigth by 5») по грамматике — просто имя переменной, но
//     errors.md показывает её как TD004. Парсер всегда возвращает Ident, а TD004 сообщает Check,
//     если имя нигде не объявлено (ни переменная, ни параметр, ни цикл, ни объект) и отличается
//     от left/right/up/down регистром или одной правкой (в нём не меньше трёх букв).
//     Переменная с именем «lift» или «Left» ошибкой не считается.
//   - Подсказки «Может быть...»: регистр игнорируется; допустимое расстояние 2 для слов от
//     5 букв, 1 для слов из 3–4 букв, 0 для коротких (чтобы не предлагать слова наугад).
//   - В «slide to x, y in T seconds» слово «in» после y — часть команды, а не оператор «входит ли»;
//     внутри скобок и списков оператор «in» работает как обычно.
//   - «for each i in a to b»: после «in» разбирается полное выражение, затем, если встретилось
//     «to», — конец диапазона (additive). Грамматика формально уже, но разницы для
//     корректных программ нет.
//   - Вызов «Hero.fly()» грамматикой не допускается (вызов — только «имя(...)»), хотя TD106
//     в errors.md говорит о командах объекта. Следуем грамматике: это ошибка TD005.
//   - «spawn» внутри аргументов вызова жадный: в «f(spawn "S" at 1, 2)» запятая принадлежит spawn.
//   - Одно и то же слово «second»/«seconds» равнозначно и в AST не сохраняется.
//   - Незакрытая «(» или «[»: если следующая строка не сдвинута глубже строки с открывающей
//     скобкой (и не начинается с закрывающей), скобка считается незакрытой, а строка — началом
//     нового оператора. Так одна забытая «)» не превращает остаток файла в одну строку.
//   - Тексты: неэкранированная «}» вне вставки — обычный символ; неизвестный спецсимвол
//     («\q») — TD005; пустая вставка «{}» — TD005; «==» и «!=» — TD005 с подсказкой про «is».
//   - Нечётный отступ после строки, открывающей блок (when, to, if, else, repeat, while, for),
//     считается попыткой сдвинуть блок: так получается одна ошибка TD001, а не две.
//   - Предел вложенности (блоки, выражения, вставки в тексте) — 64; при превышении разбор
//     останавливается с ошибкой TD005. Всего возвращается не более 20 ошибок, не более одной
//     на строку.
//   - Запятая в конце списка, аргументов или параметров запрещена, как и в грамматике:
//     TD005 «После запятой нужно значение — уберите запятую» на позиции запятой.
//   - «round» — ключевое слово (из-за «next round»), но «round(x)» разбирается как вызов функции.
//   - Пределы: цепочка из одинаковых по приоритету операций — 10 000 членов, операций в одной
//     команде — 50 000, файл — 2 МБ (иначе TD005): дерево таких цепочек глубокое, а обходчики
//     рекурсивны.
//   - Если на одной строке есть ошибка лексера и ошибка парсера, возвращается лексическая.
